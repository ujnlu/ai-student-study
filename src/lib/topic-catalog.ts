// ---------- 组装 ----------
const GRADE_CN = ["", "一", "二", "三", "四", "五", "六"];

function buildAll(): Topic[] {
  const out: Topic[] = [];
  for (const [lv, list] of Object.entries(OLY)) {
    const level = Number(lv);
    const grade = Math.ceil(level / 2);
    const semester = (level % 2 === 1 ? 1 : 2) as 1 | 2;
    list.forEach(([name, module, hint], i) => {
      const no = i + 1;
      out.push({
        code: `oly-l${level}-${String(no).padStart(2, "0")}`,
        track: "olympiad",
        subjectId: "math",
        grade,
        semester,
        level,
        no,
        module,
        moduleName: MODULES[module]?.name ?? module,
        slug: `l${level}-${no}`,
        name,
        emoji: MODULE_EMOJI(module),
        desc: `第 ${no} 讲 · ${MODULES[module]?.name ?? module}`,
        hint: hint ?? `${name}：${GRADE_CN[grade]}年级${semester === 1 ? "上" : "下"}学期奥数第 ${level} 级第 ${no} 讲的常规内容`,
        practice: "quiz",
      });
    });
  }
  for (const [g, list] of Object.entries(MATH_SPECIAL)) {
    for (const [slug, module, name, desc, hint] of list) {
      out.push({ code: `special-math-g${g}-${slug}`, track: "special", subjectId: "math", grade: Number(g), module, moduleName: MODULES[module]?.name ?? module, slug, name, emoji: MODULE_EMOJI(module), desc, hint, practice: "quiz" });
    }
  }
  for (const [g, list] of Object.entries(CHINESE)) {
    for (const [slug, module, name, desc, hint, practice] of list) {
      out.push({ code: `special-chinese-g${g}-${slug}`, track: "special", subjectId: "chinese", grade: Number(g), module, moduleName: MODULES[module]?.name ?? module, slug, name, emoji: MODULE_EMOJI(module), desc, hint, practice: practice ?? "quiz" });
    }
  }
  for (const [g, list] of Object.entries(ENGLISH)) {
    for (const [slug, module, name, desc, hint, practice] of list) {
      out.push({ code: `special-english-g${g}-${slug}`, track: "special", subjectId: "english", grade: Number(g), module, moduleName: MODULES[module]?.name ?? module, slug, name, emoji: MODULE_EMOJI(module), desc, hint, practice: practice ?? "quiz" });
    }
  }
  for (const [band, list] of Object.entries(QUALITY)) {
    const grades = band === "g12" ? [1, 2] : band === "g34" ? [3, 4] : [5, 6];
    for (const g of grades) {
      for (const [subject, slug, name, emoji, desc, hint] of list) {
        out.push({ code: `quality-${subject}-g${g}-${slug}`, track: "quality", subjectId: subject, grade: g, module: subject, moduleName: MODULES[subject]?.name ?? subject, slug, name, emoji, desc, hint, practice: "quiz" });
      }
    }
  }
  return out;
}

let ALL: Topic[] | null = null;
export function allTopics(): Topic[] {
  return (ALL ??= buildAll());
}
